import {existsSync} from 'node:fs';
import {copyFile, mkdir, readFile, readdir, rename, rm, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

// The authorized Payung Madinah mirror is archived under its original path.
// Publish it as /azura without rebuilding the large binary asset bundles.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const bundleDir = join(root, 'payungmadinah-bundles');
const manifestFile = join(bundleDir, 'manifest.json');
const legacyDir = join(root, 'public/payungmadinah');
const targetDir = join(root, 'public/azura');
const brandingDir = join(root, 'branding/azura');
if (!existsSync(manifestFile)) {
  if (!existsSync(join(targetDir, 'index.html'))) {
    throw new Error('Payung Madinah files and archive manifest are both missing');
  }
  console.log('Azura static pages available directly.');
  process.exit(0);
}

await mkdir(join(root, 'public'), {recursive: true});
const bundles = JSON.parse(await readFile(manifestFile, 'utf8'));
for (const bundle of bundles) {
  if (!/^payungmadinah-\d+\.tar\.gz$/.test(bundle.name)) throw new Error('Invalid bundle filename');
  const archive = join(bundleDir, bundle.name);
  const data = await readFile(archive);
  const digest = createHash('sha256').update(data).digest('hex');
  if (digest !== bundle.sha256) throw new Error(`Archive checksum mismatch: ${bundle.name}`);
  const entries = execFileSync('tar', ['-tzf', archive], {encoding: 'utf8'}).trim().split('\n');
  if (entries.some(path => !path.startsWith('payungmadinah/') || path.split('/').includes('..'))) {
    throw new Error(`Unexpected archive paths: ${bundle.name}`);
  }
  execFileSync('tar', ['-xzf', archive, '-C', join(root, 'public')]);
}

// This directory is generated by the bundle extraction, not a source folder.
// Replacing it makes repeated local builds deterministic.
await rm(targetDir, {recursive: true, force: true});
await rename(legacyDir, targetDir);
const brandTargetDir = join(targetDir, 'images/brand');
await mkdir(brandTargetDir, {recursive: true});
await Promise.all([
  copyFile(join(brandingDir, 'logo.webp'), join(brandTargetDir, 'azura-logo.webp')),
  copyFile(join(brandingDir, 'icon.webp'), join(brandTargetDir, 'azura-icon.webp')),
  copyFile(join(brandingDir, 'theme.css'), join(brandTargetDir, 'azura-theme.css')),
  // The source banners contain the former brand name baked into their pixels.
  copyFile(join(brandingDir, 'banner-desktop.webp'), join(targetDir, 'images/microsites/paket-umroh/banner-desktop.webp')),
  copyFile(join(brandingDir, 'banner-mobile.webp'), join(targetDir, 'images/microsites/paket-umroh/banner-mobile.webp')),
  // These source promotional pictures had the former company logo and name
  // embedded in the image itself, beyond any HTML replacement.
  ...['usp-kantor.webp', 'usp-kantor-m.webp', 'usp-manasik.webp',
    'usp-manasik-m.webp', 'usp-persiapan.webp', 'usp-perlengkapan.webp',
    'usp-perlengkapan-m.webp', 'usp-tim.webp'].map(name =>
    copyFile(join(brandingDir, name), join(targetDir, 'images/microsites/paket-umroh', name))),
  // The questions microsite repeats three of those original promotional images.
  copyFile(join(brandingDir, 'usp-perlengkapan-m.webp'), join(targetDir, 'images/microsites/tanyacs/banner-1.webp')),
  copyFile(join(brandingDir, 'usp-kantor-m.webp'), join(targetDir, 'images/microsites/tanyacs/banner-3.webp')),
  copyFile(join(brandingDir, 'usp-manasik-m.webp'), join(targetDir, 'images/microsites/tanyacs/banner-5.webp')),
]);
const textExtensions = new Set(['.html', '.css', '.js', '.json', '.svg', '.xml', '.txt', '.webmanifest']);
// Source site colors are replaced only where they are part of the original
// styling. Airline marks, photos, and other third-party assets stay intact.
const palette = new Map(Object.entries({
  '#b19167': '#D4AF37', '#c9a35f': '#D4AF37', '#d8bd94': '#D4AF37',
  '#b8924c': '#B8860B', '#b8955b': '#B8860B', '#a5855d': '#B8860B',
  '#9b7653': '#A67C52', '#8a6d3b': '#6F4E37', '#6f5d4f': '#6F4E37',
  '#faf7f1': '#FAF4E6', '#faf7f2': '#FAF4E6', '#fbf9f6': '#FAF4E6',
  '#fcfbf9': '#FAF4E6', '#f1ebdf': '#E6D5B8', '#ece7df': '#E6D5B8',
  '#e5dcd2': '#E6D5B8', '#f2ece3': '#E6D5B8',
  '#141416': '#2E2A24', '#1f2430': '#2E2A24', '#2b3035': '#2E2A24',
  '#4b5058': '#6F4E37', '#6b6258': '#6F4E37',
}));
let updatedFiles = 0;
const legacySocialAnchor = /<a\b(?=[^>]*href="[^"]*(?:instagram\.com\/payungmadinah|youtube\.com\/@payungmadinah|tiktok\.com\/@payungmadinah|threads\.com\/@payungmadinah|linkedin\.com\/company\/payungmadinahtour|facebook\.com\/profile\.php\?id(?:=|&#x3D;)100093536076397)[^"]*")[^>]*>[\s\S]*?<\/a>/gi;
async function updateInternalLinks(directory) {
  for (const entry of await readdir(directory, {withFileTypes: true})) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      await updateInternalLinks(path);
    } else if (entry.isFile() && [...textExtensions].some(ext => entry.name.endsWith(ext))) {
      const current = await readFile(path, 'utf8');
      // Remove the reference company's social destinations before translating
      // the brand, so we never fabricate social accounts under the AZURA name.
      let updated = (entry.name.endsWith('.html') ? current.replace(legacySocialAnchor, '') : current)
        // The actual name changes everywhere, including metadata and JSON-LD.
        .replace(/Payung(?:\s|&nbsp;)+Madinah\s+Umroh\s+&(?:amp;)?\s*Haji\s+Official/gi, 'AZURA Tour & Travel')
        .replace(/Payung(?:\s|&nbsp;)+Madinah/gi, 'AZURA')
        .replace(/PayungMadinah/g, 'AZURA')
        // Query strings and prefilled WhatsApp messages encode spaces.
        .replace(/Payung(?:\+|%20)Madinah/gi, 'AZURA')
        .replace(/AZURA\s+Umroh\s+&(?:amp;)?\s*Haji\s+Official/gi, 'AZURA Tour & Travel')
        .replace(/(<span class="bp">AZURA<\/span>)\s*Umroh\s+&(?:amp;)?\s*Haji\s+Official/gi, '$1 Tour &amp; Travel')
        // Old recruitment email must not receive AZURA-branded applications.
        .replace(/mailto:payungmadinah\.recruitment@gmail\.com(?:\?[^"'<\s]*)?/gi, 'https://wa.me/6285222005585?text=Assalamualaikum%2C%20saya%20ingin%20bertanya%20tentang%20karir%20AZURA')
        .replace(/payungmadinah\.recruitment@gmail\.com/gi, '+62 852-2200-5585')
        .replace(/Kirim CV & lamaran \(PDF\) ke/gi, 'Informasi lamaran melalui WhatsApp')
        .replace(/Kirim CV dan lamaran \(PDF\) ke/gi, 'Tanyakan lamaran melalui WhatsApp')
        .replace(/Salin alamat email rekrutmen/gi, 'Salin nomor WhatsApp AZURA')
        // Update old public links without changing unrelated email domains.
        .replace(/https?:\/\/(?:www\.)?payungmadinah\.id/gi, 'https://pesonaflix.vercel.app/azura')
        .replace(/https%3A%2F%2F(?:www\.)?payungmadinah\.id/gi, 'https%3A%2F%2Fpesonaflix.vercel.app%2Fazura')
        .replace(/(?:www\.)?payungmadinah\.id/gi, 'pesonaflix.vercel.app/azura')
        // A path slash followed by "payungmadinah" is a route, not a domain.
        .replace(/\/payungmadinah(?=\/|[?#"'\s<]|$)/gi, '/azura')
        .replaceAll('/azura/images/microsites/paket-umroh/logo.webp', '/azura/images/brand/azura-logo.webp')
        .replaceAll('/azura/images/microsites/tanyacs/logo.webp', '/azura/images/brand/azura-logo.webp')
        .replaceAll('/azura/images/logo-main.svg?v2.0', '/azura/images/brand/azura-logo.webp')
        .replaceAll('/azura/images/favicon.png', '/azura/images/brand/azura-icon.webp')
        .replaceAll('/azura/images/apple-touchs.png', '/azura/images/brand/azura-icon.webp')
        .replaceAll('/azura/images/apple-touch-icon-180.png', '/azura/images/brand/azura-icon.webp');
      if (entry.name.endsWith('.html') || entry.name.endsWith('.css')) {
        updated = updated.replace(/#[0-9a-f]{6}\b/gi, color => palette.get(color.toLowerCase()) ?? color);
      }
      if (entry.name.endsWith('.html')) {
        // A historical event photo still shows the former operator's backdrop
        // and permit details; it must not be relabelled as an AZURA event.
        updated = updated.replace(/<li class="slide mslide">\s*<img[^>]*\/azura\/images\/microsites\/paket-umroh\/manasik-backdrop\.webp[\s\S]*?<\/li>/gi, '');
        // The reference site's social accounts do not belong to AZURA.
        updated = updated.replace(/<meta\s+name="twitter:(?:site|creator)"\s+content="@payungmadinah"\s*\/?\s*>/gi, '');
        updated = updated.replace(/@payungmadinah/gi, 'kanal resmi AZURA (segera hadir)');
        // Social screenshots contain account names and follower counts from
        // the old brand; replace them with non-claiming AZURA visual panels.
        updated = updated.replace(/<img\b[^>]*src="\/azura\/images\/socials\/([^"/]+)"[^>]*>/gi, (_, filename) => {
          const platform = ({'sosialmedia.jpg': 'Kanal Digital', 'instagram.jpg': 'Instagram', 'tiktok.jpg': 'TikTok', '1.png': 'Facebook', '2.png': 'LinkedIn', '3.png': 'Threads'})[filename] || 'Media Sosial';
          return `<div class="azura-social-visual"><img loading="lazy" src="/azura/images/brand/azura-logo.webp" alt="Logo AZURA Tour & Travel"><span>${platform} — segera hadir</span></div>`;
        });
        // Old social contest screenshots name an unrelated account. Display a
        // neutral channel panel instead of implying the campaign is live.
        updated = updated.replace(/<img\b[^>]*src="\/azura\/images\/campaign\/umroh_gratis_ajak_threads\.jpg"[^>]*>/gi,
          '<div class="azura-social-visual"><img src="/azura/images/brand/azura-logo.webp" alt="AZURA Tour & Travel"><span>Informasi program melalui WhatsApp AZURA</span></div>');
        if (path.endsWith('/sosial-media/index.html')) {
          updated = updated
            .replace(/<title>[^<]*<\/title>/i, '<title>Sosial Media | AZURA Tour & Travel</title>')
            .replace(/Ikuti perjalanan, informasi, dan inspirasi spiritual terbaru langsung dari sosial media resmi kami\./gi, 'Kanal sosial resmi AZURA akan diumumkan segera. Untuk informasi saat ini, hubungi tim kami melalui WhatsApp.');
        }
        updated = updated.replace(/<\/head>/i, '<link rel="stylesheet" href="/azura/images/brand/azura-theme.css"></head>');
      }
      if (updated !== current) {
        await writeFile(path, updated);
        updatedFiles++;
      }
    }
  }
}
await updateInternalLinks(targetDir);
console.log(`Azura restored from ${bundles.length} archive files; updated links in ${updatedFiles} text files.`);
